const { chromium } = require("playwright"); const fs = require("fs");
const results = []; const check = (n, ok, x = "") => { results.push(!!ok); console.log((ok ? "PASS " : "FAIL ") + n + (x ? "  — " + x : "")); };
(async () => {
  const b = await chromium.launch({ args: ["--no-sandbox", "--disable-dev-shm-usage"] });
  const c = await b.newContext({ viewport: { width: 1280, height: 900 } });
  await c.addCookies([{ name: "_roki_key", value: fs.readFileSync("/tmp/e2e-cookie.txt", "utf8"), domain: "roki.ee", path: "/", secure: true, httpOnly: true, sameSite: "Lax" }]);
  const p = await c.newPage(); const errs = []; p.on("pageerror", e => errs.push(String(e)));
  await p.goto("https://roki.ee/title/movie/10331"); await p.waitForSelector("button.btn-lg:visible"); await p.click("button.btn-lg:visible");
  await p.waitForSelector("#external-panel", { timeout: 150000 });
  const res = async () => (await p.evaluate(() => [...document.querySelectorAll("section ul li .badge-primary")].map(e => e.textContent.trim())));
  const ext = await res();
  check("external: everything is listed, 4K included", ext.includes("4K") && ext.length >= 4, JSON.stringify(ext));
  await p.click("button:has-text('Browser'):visible"); await p.waitForTimeout(1200);
  const br = await res();
  check("browser: nothing above 1080p", br.length > 0 && !br.includes("4K"), JSON.stringify(br));
  check("browser: the external panel is gone", (await p.locator("#external-panel").count()) === 0);
  check("browser: it says what is hidden", (await p.locator("text=hidden").count()) >= 1);
  check("browser: buttons say Play", (await p.locator("section ul li button:has-text('Play')").count()) >= 1 && (await p.locator("section ul li button:has-text('Open')").count()) === 0);
  await p.click("button:has-text('External player'):visible"); await p.waitForTimeout(1200);
  const back = await res();
  check("external again: the 4K ones are back", back.includes("4K") && back.length === ext.length);
  await p.click("button:has-text('Browser'):visible"); await p.waitForTimeout(800);
  await p.click("section ul li button:has-text('Play') >> nth=0");
  await p.waitForURL(/\/watch\/movie\/10331\?h=/, { timeout: 30000 });
  check("browser: choosing opens the player page at once (no refresh needed)", true);
  await p.waitForSelector("#study-video", { timeout: 60000 });
  await p.waitForFunction(() => { const v = document.getElementById("study-video"); return v && v.currentTime > 1; }, null, { timeout: 90000 });
  check("browser: and it plays", true);
  check("no page errors", errs.length === 0, errs.join("|"));
  console.log(`${results.filter(Boolean).length}/${results.length} passed`);
  await b.close(); process.exit(results.every(Boolean) ? 0 : 1);
})();
