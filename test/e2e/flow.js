const { chromium } = require("playwright"); const fs = require("fs");
const results = []; const check = (n, ok, x = "") => { results.push(!!ok); console.log((ok ? "PASS " : "FAIL ") + n + (x ? "  — " + x : "")); };
const cookie = () => [{ name: "_roki_key", value: fs.readFileSync("/tmp/e2e-cookie.txt", "utf8"), domain: "roki.ee", path: "/", secure: true, httpOnly: true, sameSite: "Lax" }];
(async () => {
  const b = await chromium.launch({ args: ["--no-sandbox", "--disable-dev-shm-usage", "--autoplay-policy=no-user-gesture-required"] });
  const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } }); await ctx.addCookies(cookie());
  await ctx.addInitScript(() => { if (!localStorage.getItem("roki:player")) localStorage.setItem("roki:player", "browser"); window.__launched = []; window.addEventListener("phx:roki:launch", e => window.__launched.push(e.detail.url)); });
  const p = await ctx.newPage(); const errs = []; p.on("pageerror", e => errs.push(String(e)));
  await p.goto("https://roki.ee/title/movie/10331"); await p.waitForSelector("button.btn-lg:visible", { timeout: 30000 });
  await p.click("button.btn-lg:visible");
  await p.waitForURL(/\/sources\/movie\/10331/, { timeout: 15000 });
  check("Play on a film opens its sources page", /\/sources\/movie\/10331/.test(p.url()), p.url());
  await p.waitForTimeout(1200);
  check("the address is cleaned of ?auto=1", !/auto=1/.test(p.url()), p.url());
  const sawModal = await p.locator("#auto-start").count();
  console.log("modal seen at 1.2s:", sawModal);
  await p.waitForURL(/\/watch\/movie\/10331/, { timeout: 150000 });
  check("auto-start opened the player page", /\/watch\/movie\/10331/.test(p.url()), p.url());
  await p.waitForSelector("#study-video", { timeout: 60000 });
  check("the player and the subtitle sidebar are on it", (await p.locator("#study-sidebar").count()) === 1);
  await p.waitForFunction(() => { const v = document.getElementById("study-video"); return v && v.currentTime > 1; }, null, { timeout: 90000 });
  check("it plays", true);
  await p.waitForFunction(() => /[?&]h=[0-9a-f]{40}/i.test(location.search), null, { timeout: 15000 });
  const url = p.url(); check("the address names the release", /h=[0-9a-f]{40}/i.test(url), url);
  await p.reload(); await p.waitForSelector("#study-video", { timeout: 60000 });
  check("reload stays on the player", /\/watch\/movie\/10331\?h=/.test(p.url()));
  await p.goBack(); await p.waitForTimeout(3000);
  check("back goes to the sources", /\/sources\/movie\/10331/.test(p.url()), p.url());
  await p.waitForSelector("text=Releases", { timeout: 60000 });
  check("and does not start anything again (list, no pop-up)", (await p.locator("#auto-start").count()) === 0 && /sources/.test(p.url()));
  console.log("errors", errs.slice(0, 4));
  check("no page errors", errs.length === 0);
  console.log(`${results.filter(Boolean).length}/${results.length} passed`);
  await b.close(); process.exit(results.every(Boolean) ? 0 : 1);
})();
