defmodule RokiWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :roki

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_roki_key",
    signing_salt: "LdpSyesq",
    same_site: "Lax",
    # Without this the cookie lasts as long as the browser session, which for a web app on a
    # phone means until the phone decides to stop it — and then the site is signed out again, a
    # few times a day. Sixty days, the same window the remember-me cookie uses, so the two
    # expire together rather than one outliving the other.
    max_age: 60 * 60 * 24 * 60
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [:peer_data, :x_headers, session: @session_options]],
    longpoll: [connect_info: [:peer_data, :x_headers, session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :roki,
    gzip: not code_reloading?,
    only: RokiWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :roki
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  # The sync key is in the address; keep it out of the request log.
  plug :hide_sync_key

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    # /api/laev/* stores request bodies byte for byte: the raw bytes are kept before parsing.
    body_reader: {RokiWeb.RawBodyReader, :read_body, []},
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug RokiWeb.Router

  # The log line is built from `request_path`; routing reads `path_info`, which stays as it is.
  defp hide_sync_key(%Plug.Conn{path_info: ["api", "laev", _key | rest]} = conn, _opts),
    do: %{conn | request_path: "/" <> Enum.join(["api", "laev", "[key]" | rest], "/")}

  defp hide_sync_key(conn, _opts), do: conn
end
